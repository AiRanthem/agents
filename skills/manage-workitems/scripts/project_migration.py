def _hash(data):
    return hashlib.sha256(data).hexdigest() if data is not None else None


# Compatibility evidence: hashes of the two exact v2 migration routes and the
# initial v2 initializer assets, before workflow/recovery joined generated_sha256.
# Unknown content remains blocked; a marker alone never authorizes replacement.
LEGACY_V2_ROUTE_HASHES = {
    '.project/workflow.md': {
        '34dab8878b69a0877e03237e7a1d873a491a323179bccc8a440120d3713f0926',
        '9034a26c4174f2f0378bff301e892a64919f20896f862f3a325dd479a40de5d1',
    },
    '.project/recovery.md': {
        '95bb365355a9ea2753037bee2fcb0d1590094686e1c69d1729f653e07e55289f',
        '14284d1bd3be0db819ca5ec5b8d713645df987ab53cbe3981c02ce69f712ae55',
    },
}


def _legacy_generated_entry(name, data, project):
    known = LEGACY_V2_ROUTE_HASHES.get(name, set())
    if _hash(data) in known:
        return True
    text = data.decode('utf-8')
    if name == '.project/workflow.md':
        text = text.replace('Follow the delivery requirements recorded in each work item.',
                            '{{DELIVERY_CONVENTIONS}}')
    elif name == '.project/recovery.md':
        text = text.replace(
            f"dedicated branch `{project['storage']['branch']}` from `{project['storage']['url']}`",
            'dedicated branch `{{STORAGE_BRANCH}}` from `{{STORAGE_URL}}`')
        text = text.replace(f'dev-kit from `{templates.DEVKIT_SOURCE}`',
                            'dev-kit from `{{DEVKIT_SOURCE}}`')
    return _hash(text.encode('utf-8')) in known


def generation_record(files):
    """Bind generated bytes and the actual installed renderer/template sources."""
    sources = {'project_migration.py': _hash(Path(__file__).read_bytes()),
               'project_templates.py': _hash(Path(templates.__file__).read_bytes())}
    sources.update({name: _hash((templates.TEMPLATE_ROOT / name).read_bytes())
                    for name in templates.GENERATED_PROJECT_PATHS})
    fingerprint = '\n'.join(f'{name}:{digest}' for name, digest in sorted(sources.items()))
    return {'instruction_policy': 'current-only',
            'generator_version': GENERATOR_VERSION,
            'generator_sha256': _hash(fingerprint.encode('utf-8')),
            'generator_sources_sha256': sources,
            'generated_sha256': {name: _hash(files[name]) for name in sorted(files)
                                if name in {*templates.GENERATED_PROJECT_PATHS, '.project/project-instructions.md'}
                                or name.startswith('workitems/') and name.endswith('/AGENTS.md')}}


def root_entry(project):
    return templates.render_template('AGENTS.md', project)


def item_entry(identifier):
    return f'''# Work item {identifier}

Use the project root's generated `AGENTS.md` and its resolved project command entrypoint, retaining the caller's identity and command prefix. For the requested Markdown workflow operation on `{identifier}`, run `begin OP {identifier}` with typed inputs. Read its complete `read` payload and required original external instructions, edit only its absolute `editable` Markdown paths, and execute the returned `finish_command` unchanged; review and reuse checkpoints supply only their program-declared result, provenance and applicable contract-preservation or mechanical-correction arguments after assessment.

`published` or `no_op` ends the operation; the design owner continues any outstanding approval handoff; `partial` permits only the returned resume command; `blocked` with `code: stale_ticket` permits only its returned begin command; expired tickets carrying authorization or review evidence return `code: stale_evidence` without a continuation command; otherwise report the listed blockers or missing facts and stop the affected operation. YAML, state, guards, ownership, review bindings, dependency/fix gates and Git/Aone publication belong to the program. The spec is the complete current design without machine-status frontmatter. A migrated label or old review cannot establish current approval, independence or implementation permission. Use the root command contract for direct execution handoff, source-generation replacement and internal-resource lifecycle commands. Preserve the user's code-submission and external-action boundaries.
'''


def project_instructions(files):
    routes = [name for name in ('.project/context.md', '.project/main-workspace.md',
                               '.project/business-instructions.md') if name in files]
    return ("# Current project instructions\n\n"
            "The program includes these current project sources in the operation's read payload for business background, constraints and main-workspace routes:\n\n"
            + ''.join(f'- `{name}`\n' for name in routes)
            + "\nKeep only current effective requirements, design, decisions, knowledge and business instructions in project documents. Replace superseded content; Git retains earlier versions. Keep current approval, delivery and unresolved recovery records. The generated entrypoints and installed skills define the shared protocol.\n"
            + "\nRead required original main-workspace instructions before dependent work. Preserve explicit permission, delivery and environment constraints. Migration grants no design approval, implementation authorization, independent review or delivery evidence.\n")


def _frontmatter(data, name):
    lines = data.splitlines(keepends=True)
    if not lines or lines[0].strip() != b'---':
        return None, data
    for index, line in enumerate(lines[1:], 1):
        if line.strip() == b'---':
            value = store.load_yaml(b''.join(lines[1:index]), name)
            if value is None:
                value = {}
            if not isinstance(value, dict):
                raise runtime.ProjectError(name + ': legacy frontmatter must be a mapping')
            return value, b''.join(lines[index + 1:])
    raise runtime.ProjectError(name + ': unterminated legacy frontmatter')


def _put(writes, files, name, text):
    data = text.encode('utf-8') if isinstance(text, str) else text
    if files.get(name) != data:
        writes[name] = data.decode('utf-8')


def _blockers(files):
    blocked = []
    for identifier, record in store.items(files).items():
        if not store.is_v2(files):
            conflicts = set(record) & {'design', 'blockers'}
            if conflicts:
                blocked.append(f'{identifier}: legacy extension collides with v2 fields {sorted(conflicts)}; explicit reconciliation required')
            if 'documents' in record and not isinstance(record['documents'], dict):
                blocked.append(f'{identifier}: legacy documents extension is not a mapping; explicit reconciliation required')
            elif any(key in record.get('documents', {}) and record['documents'][key] != key + '.md'
                     for key in ('requirement', 'context', 'decision', 'logs')):
                blocked.append(f'{identifier}: legacy document routes conflict with the fixed v2 layout; explicit reconciliation required')
            if isinstance(record.get('development'), dict) and 'legacy_source_hash' in record['development']:
                blocked.append(f'{identifier}: legacy development already contains legacy_source_hash; explicit reconciliation required')
        receipt = store.receipt(files, identifier)
        if receipt and receipt.get('state') != 'verified':
            blocked.append(f'{identifier}: unresolved synchronization {receipt.get("state")!r}; reconcile before migration')
    return blocked


def _instructions_required(sources, *, custom=False):
    return {'status': 'blocked',
            'code': 'unsupported-custom-instructions' if custom else 'current-instructions-required',
            'blockers': sorted(set(sources)), 'read_sources': sorted(set(sources)),
            'writes': {}, 'checks': {},
            'action': 'Read these sources and supply their current effective business constraints through instructions_file. Maintain existing authorization boundaries; the migration does not infer Markdown semantics.'}


def validate_publication(bundle, current, prospective):
    """Permit only the exact deterministic migration under unchanged claims."""
    instructions = prospective.get('.project/business-instructions.md')
    prepared = prepare_migration(current, instructions=instructions.decode('utf-8') if instructions is not None else None)
    if prepared['status'] not in {'prepared', 'no_op'}:
        raise runtime.ProjectError('migration publication requires a valid deterministic candidate')
    expected = store.apply_writes(current, prepared['writes'])
    actual = dict(prospective)
    actor = {key: bundle[key] for key in ('session', 'token')}
    for identifier, item in store.items(expected).items():
        name = store.receipt_path(expected, identifier)
        receipt = store.receipt(actual, identifier)
        if receipt and receipt.get('migration_sync') == actor and receipt.get('state') == 'pending':
            planned = copy.deepcopy(store.receipt(current, identifier) or {})
            planned.update(intent_id=receipt.get('intent_id'), state='pending',
                           content_sha256=runtime._business_digest(expected, identifier),
                           external_id=planned.get('external_id'), baseline_fields=planned.get('baseline_fields'),
                           git_source_commit=None, checked_at=None, release_owner=copy.deepcopy(item.get('owner')),
                           migration_sync=actor)
            planned.pop('operation', None)
            if receipt != planned:
                raise runtime.ProjectError('migration synchronization must preserve the original owner and content')
            if name in expected:
                actual[name] = expected[name]
            else:
                actual.pop(name, None)
        elif receipt and receipt.get('state') == 'verified' and name in expected:
            planned = dict(store.receipt(expected, identifier),
                           content_sha256=runtime._business_digest(expected, identifier))
            if receipt == planned:
                actual[name] = expected[name]
    if actual != expected or any(bundle['checks'].get(name, 'missing') != digest
                                 for name, digest in prepared['checks'].items()):
        raise runtime.ProjectError('migration publication differs from the guarded deterministic candidate')


def sync_publication(bundle, current, prospective, identifier):
    """A migration sync identity may update its receipt, never the item claim."""
    receipt = store.receipt(current, identifier)
    actor = {key: bundle[key] for key in ('session', 'token')}
    if not receipt or receipt.get('state') not in {'pending', 'unknown'} or receipt.get('migration_sync') != actor:
        return False
    updated = store.receipt(prospective, identifier)
    immutable = ('intent_id', 'content_sha256', 'release_owner', 'migration_sync')
    if not updated or any(updated.get(key) != receipt.get(key) for key in immutable):
        return False
    receipts = {store.receipt_path(current, value) for value in store.items(current)}
    return ({name: data for name, data in current.items() if name not in receipts} ==
            {name: data for name, data in prospective.items() if name not in receipts} and
            receipt.get('content_sha256') == runtime._business_digest(prospective, identifier))


def _minimal_provenance(marker, files):
    entries, sources = {}, {}
    for identifier, record in store.items(files).items():
        development = record.get('development')
        if not isinstance(development, dict) or 'legacy_source_hash' not in development:
            continue
        digest = development['legacy_source_hash']
        original_entries = marker.get('legacy_developments', {})
        original_sources = marker.get('source_sha256', {})
        entry = original_entries.get(identifier) if isinstance(original_entries, dict) else None
        source = f'workitems/{identifier}/item.json'
        if (not isinstance(original_sources, dict) or not isinstance(entry, dict) or entry.get('source_sha256') != digest or
                not isinstance(entry.get('development'), dict) or
                original_sources.get(source) != digest):
            raise store.StoreError(identifier + ': current legacy development requires authenticated migration provenance')
        entries[identifier], sources[source] = entry, digest
    for name in ('history', 'approved_instructions_sha256', 'source_sha256', 'legacy_developments',
                 'from_schema', 'to_schema'):
        marker.pop(name, None)
    if entries:
        marker.update(from_schema=1, to_schema=2, legacy_developments=entries, source_sha256=sources)


def _upgrade_cleanup(files, writes):
    """Bind the newest unambiguous existing disposition before pruning old pairs."""
    for identifier, item in store.items(files).items():
        workflow = item.get('workflow') or {}
        if workflow.get('cleanup_record') is not None:
            continue
        prefix = f'workitems/{identifier}/records/'
        candidates = []
        for name, data in files.items():
            if not name.startswith(prefix) or not name.endswith('.yaml'):
                continue
            record = store.load_yaml(data, name)
            if not isinstance(record, dict) or record.get('kind') != 'cleanup':
                continue
            if record.get('status') != item.get('cleanup'):
                continue
            record_id = Path(name).stem
            report = prefix + record_id + '.md'
            if (record.get('id') != record_id or record.get('item', identifier) != identifier or
                    report not in files or not isinstance(record.get('created_at'), str)):
                raise store.StoreError(identifier + ': legacy cleanup disposition is inconsistent')
            try:
                created = datetime.fromisoformat(record['created_at'].replace('Z', '+00:00'))
            except ValueError as exc:
                raise store.StoreError(identifier + ': legacy cleanup timestamp is invalid') from exc
            if created.tzinfo is None:
                raise store.StoreError(identifier + ': legacy cleanup timestamp requires timezone')
            candidates.append((created, name, record))
        if not candidates:
            continue
        newest = max(candidate[0] for candidate in candidates)
        selected = [candidate for candidate in candidates if candidate[0] == newest]
        if len(selected) != 1:
            raise store.StoreError(identifier + ': legacy cleanup dispositions are ambiguous')
        _, name, record = selected[0]
        record['item'] = identifier
        _put(writes, files, name, store.dump_yaml(record))
        item.setdefault('workflow', {})['cleanup_record'] = record['id']
        writes.update(store.write_item(files, item))


def prepare_migration(files, *, instructions=None):
    """Prepare current canonical documents and credentials; Git keeps history."""
    files = dict(files)
    blocked = _blockers(files)
    if blocked:
        return {'status': 'blocked', 'blockers': blocked, 'writes': {}, 'checks': {}}
    config = store.project(files)
    v2_source = store.is_v2(files)
    writes = {}
    marker_name = '.project/migration.yaml'
    marker = store.load_yaml(files[marker_name], marker_name) if marker_name in files else {}
    if not isinstance(marker, dict) or not isinstance(marker.get('generated_sha256', {}), dict):
        raise runtime.ProjectError(marker_name + ': marker and generated_sha256 must be mappings')
    if v2_source:
        entries = templates.project_entries(config)
        entries['.project/project-instructions.md'] = project_instructions(files)
        entries.update({f'workitems/{identifier}/AGENTS.md': item_entry(identifier)
                        for identifier in store.items(files)})
        custom = [name for name, text in entries.items() if name in files and
                  files[name] != text.encode('utf-8') and
                  _hash(files[name]) != marker.get('generated_sha256', {}).get(name) and
                  not _legacy_generated_entry(name, files[name], config)]
    else:
        if config.get('schema_version') != 1:
            raise runtime.ProjectError('migration requires schema_version 1 or 2')
        normalized = files.get('AGENTS.md', b'').decode('utf-8').replace(
            config['name'], '{{PROJECT_NAME}}').replace(config['id'], '{{PROJECT_ID}}')
        custom = [] if _hash(normalized.encode()) in LEGACY_ENTRY_HASHES else ['AGENTS.md']
        custom.extend(name for name in files if name.startswith('workitems/') and name.endswith('/AGENTS.md'))
    if custom and instructions is None:
        return _instructions_required(custom, custom=True)
    current_sources = []
    if v2_source:
        if marker.get('instruction_policy') != 'current-only' and '.project/business-instructions.md' in files:
            current_sources.append('.project/business-instructions.md')
    else:
        current_sources.extend(name for name in ('.project/business-instructions.md', '.project/workflow.md',
                                                '.project/recovery.md') if files.get(name))
    for identifier, record in store.items(files).items():
        spec = f'workitems/{identifier}/spec.md'
        frontmatter = None
        if not v2_source:
            frontmatter, _ = _frontmatter(files.get(spec, b''), spec)
        legacy = record.get('design', {}).get('legacy_frontmatter') or {}
        if set(frontmatter or {}) - {'design_status'} or set(legacy) - {'design_status'}:
            current_sources.append(spec if frontmatter else store.item_path(files, identifier))
    if current_sources and instructions is None:
        return _instructions_required(current_sources)
    if not v2_source:
        config = copy.deepcopy(config)
        config['schema_version'] = 2
        writes['.project/project.json'] = None
        _put(writes, files, '.project/project.yaml', store.dump_yaml(config))
    interim = store.apply_writes(files, writes)
    for identifier, original in store.items(files).items():
        record = copy.deepcopy(original)
        prefix = f'workitems/{identifier}/'
        spec = prefix + 'spec.md'
        if not v2_source:
            frontmatter, body = _frontmatter(files.get(spec, b''), spec)
            if isinstance(original.get('development'), dict):
                source_hash = _hash(files[prefix + 'item.json'])
                marker.setdefault('source_sha256', {})[prefix + 'item.json'] = source_hash
                marker.setdefault('legacy_developments', {})[identifier] = {
                    'source_sha256': source_hash, 'development': copy.deepcopy(original['development'])}
                record['development']['legacy_source_hash'] = source_hash
            state = (frontmatter or {}).get('design_status', 'draft')
            if state not in {'draft', 'review-pending', 'implementable'}:
                raise runtime.ProjectError(spec + ': unsupported legacy design_status; explicit reconciliation required')
            record['design'] = {'file': 'spec.md', 'version': 1 if spec in files else 0, 'state': state}
            writes[prefix + 'item.json'] = None
            if frontmatter is not None:
                _put(writes, files, spec, body)
        else:
            record.get('design', {}).pop('legacy_frontmatter', None)
        documents = record.setdefault('documents', {})
        for old, new in (('decisions.md', 'decision.md'), ('handoff.md', 'context.md')):
            source, destination = prefix + old, prefix + new
            if source in files:
                if destination not in files:
                    _put(writes, files, destination, files[source])
                writes[source] = None
            documents.update({key: new for key, value in documents.items() if value == old})
        for document, heading in (('requirement', 'Requirement'), ('context', 'Context'),
                                  ('decision', '当前决策'), ('logs', '当前重要记录')):
            name = prefix + document + '.md'
            if name not in files and name not in writes:
                _put(writes, files, name, '# ' + heading + '\n')
            documents[document] = document + '.md'
        # This exact generated migration narrative is obsolete; user logs are current prose.
        logs = prefix + 'logs.md'
        if _hash(files.get(logs)) == '939ecc8fc0e4444db73aa51f1a2ddd000e85dcb4fc5a0b6a160d89f06bf1dc08':
            _put(writes, files, logs, '# 当前重要记录\n')
        if spec in files:
            documents.setdefault('spec', 'spec.md')
        writes.update({name: text for name, text in store.write_item(interim, record).items()
                       if files.get(name) != text.encode('utf-8')})
        if not v2_source:
            receipt = store.receipt(files, identifier)
            if receipt is not None:
                writes[f'.project/sync/{identifier}.json'] = None
                writes.update(store.write_receipt(interim, identifier, receipt))
    interim = store.apply_writes(files, writes)
    if '.project/graph.yaml' not in files:
        _put(writes, files, '.project/graph.yaml', store.dump_yaml({'revision': 0}))
    for name, text in templates.project_entries(config).items():
        _put(writes, files, name, text)
    for identifier in store.items(interim):
        _put(writes, files, f'workitems/{identifier}/AGENTS.md', item_entry(identifier))
    if instructions is not None:
        _put(writes, files, '.project/business-instructions.md', instructions)
    for name in files:
        if name.startswith('.project/history/'):
            writes[name] = None
    for name in files:
        if name.startswith('evidence/') and name.endswith('.json'):
            metadata = store._object(files, name)
            body = name[:-5] + '.md'
            if metadata.get('body') != body or body not in files:
                raise store.StoreError(name + ': current knowledge requires its same-id Markdown body')
            _put(writes, files, name[:-5] + '.yaml', store.dump_yaml(metadata))
            writes[name] = None
    prospective = store.apply_writes(files, writes)
    _upgrade_cleanup(prospective, writes)
    prospective = store.apply_writes(files, writes)
    writes.update(retention.prune_records(prospective))
    prospective = store.apply_writes(files, writes)
    _minimal_provenance(marker, prospective)
    _put(writes, files, '.project/project-instructions.md', project_instructions(prospective))
    marker.update(generation_record(store.apply_writes(files, writes)))
    _put(writes, files, marker_name, store.dump_yaml(marker))
    checks = {name: _hash(data) for name, data in files.items()}
    checks.update({name: _hash(files.get(name)) for name in writes})
    return {'status': 'prepared' if writes else 'no_op', 'from_schema': 2 if v2_source else 1,
            'to_schema': 2, 'writes': writes, 'checks': checks,
            'items': sorted(store.items(interim))}


def _intent_path(root, operation):
    if not isinstance(operation, str) or not re.fullmatch(r'[0-9a-f]{32}', operation):
        raise runtime.ProjectError('invalid migration operation identifier')
    path = root / '.project-local' / 'migrations' / (operation + '.json')
    runtime._no_links(root, path.relative_to(root).as_posix())
    return path


def pending(root):
    """Expose retained migration intents, including failures before a Git journal."""
    runtime._no_links(root, '.project-local/migrations')
    result = []
    for path in sorted((root / '.project-local/migrations').glob('*.json')):
        record = _read_intent(root, path.stem)
        if record.get('state') != 'not_published' and record['result']['status'] != 'published':
            result.append({'operation': path.stem, 'paths': sorted(record['result']['writes']),
                           'validated': record['result'].get('validated', False)})
    return result


def _read_intent(root, operation):
    record = runtime.read_json(_intent_path(root, operation))
    if not isinstance(record, dict) or not isinstance(record.get('result'), dict) or not isinstance(record.get('identity'), dict):
        raise runtime.ProjectError('invalid retained migration operation')
    result, identity = record['result'], record['identity']
    if (result.get('migration_operation') != operation or result.get('validated') is not True or
            identity.get('session') != 'project-migration' or identity.get('token') != operation or identity.get('migration') is not True):
        raise runtime.ProjectError('retained migration identity or validation does not match its operation')
    runtime._validate_bundle(dict(identity, writes=result.get('writes'), checks=result.get('checks'), message='Resume migration'))
    return record


def _publish_intent(root, record, publish):
    result = record['result']
    for key in ('error', 'code', 'permission_path', 'required_access', 'completion', 'recovery_result',
                'authority', 'outstanding_paths', 'retry_allowed'):
        result.pop(key, None)
    try:
        publication = publish(root, result['writes'], record['identity'],
                              'Migrate project metadata and generated entrypoints to schema v2', checks=result['checks'])
    except (runtime.ProjectError, OSError, ValueError) as exc:
        publication = {'status': 'partial', 'error': str(exc)}
        if isinstance(exc, runtime.ProjectPermissionError):
            publication.update(code='host_permission_required', permission_path=exc.path, required_access='write')
    result.update(publication=publication, status=publication.get('status', 'partial'))
    if result['status'] == 'no_op' or (result['status'] == 'published' and not publication.get('verified_remote_commit')):
        result.update(status='partial', completion='unverified')
    runtime._write_journal(_intent_path(root, result['migration_operation']), record)
    return result


def resume(root, operation, *, publish, recover, inspect):
    """Recover the retained migration, proving completion against its original writes."""
    root = runtime.find_project(root)
    record = _read_intent(root, operation)
    result, identity = record['result'], record['identity']
    # Never regenerate the candidate from newer installed sources during recovery.
    journal = (result.get('publication', {}).get('recovery') or {}).get('journal')
    try:
        recovered = (runtime.resume_publication(root, session=identity['session'], token=identity['token'], journal=journal)
                     if journal else recover(root, identity['session'], identity['token']))
        if journal and recovered.get('status') in {'published', 'no_op'}:
            recovered = recover(root, identity['session'], identity['token'])
        if recovered.get('code') == 'publication_rejected_before_push':
            authority = inspect(root)
            if not authority.get('pending_publications') and not authority.get('pending_sync'):
                record['state'] = 'not_published'
                result.update(status='blocked', code='migration_not_published', completion='incomplete',
                              recovery_result=recovered, authority=authority, retry_allowed=True)
                runtime._write_journal(_intent_path(root, operation), record)
                return result
        if recovered.get('status') in {'partial', 'blocked'}:
            result.update(status=recovered['status'], recovery_result=recovered)
            runtime._write_journal(_intent_path(root, operation), record)
            return result
        authority = inspect(root)
    except (runtime.ProjectError, OSError, ValueError) as exc:
        result.update(status='partial', error=str(exc), completion='unverified')
        if isinstance(exc, runtime.ProjectPermissionError):
            result.update(code='host_permission_required', permission_path=exc.path, required_access='write')
        runtime._write_journal(_intent_path(root, operation), record)
        return result
    other_migrations = [entry for entry in authority.get('pending_migrations', []) if entry['operation'] != operation]
    if authority.get('pending_publications') or authority.get('pending_sync') or other_migrations:
        result.update(status='blocked', code='migration_recovery_pending', authority=authority, completion='incomplete')
    else:
        files = runtime._working_files(root)
        outstanding = [name for name, value in result['writes'].items()
                       if not name.startswith('.project/sync/') and files.get(name) !=
                       (value.encode('utf-8') if value is not None else None)]
        if not outstanding:
            result.update(status='published', completion='original_changes_verified',
                          verified_remote_commit=authority['commit'],
                          publication={'status': 'published', 'verified_remote_commit': authority['commit']})
            for key in ('error', 'code', 'permission_path', 'required_access', 'authority',
                        'recovery_result', 'outstanding_paths', 'retry_allowed'):
                result.pop(key, None)
        elif recovered.get('status') == 'no_op' and result['status'] != 'published':
            # No publication or backend transaction remains. Submit the same
            # saved intent; ordinary byte guards reject any changed assumptions.
            return _publish_intent(root, record, publish)
        else:
            result.update(status='blocked', code='migration_changes_unverified', outstanding_paths=outstanding,
                          completion='incomplete', authority=authority)
    runtime._write_journal(_intent_path(root, operation), record)
    return result


def migrate(root, *, dry_run=False, publish=None, instructions_file=None):
    root = runtime.find_project(root)
    retained = pending(root)
    if retained and not dry_run:
        if len(retained) != 1:
            return {'status': 'blocked', 'code': 'migration_operation_ambiguous', 'pending_migrations': retained}
        return _read_intent(root, retained[0]['operation'])['result']
    runtime._check_tracked_paths(root)
    files = runtime._working_files(root)
    errors = runtime._validate_files(root, files)
    if errors:
        raise runtime.ProjectError('invalid migration source:\n' + '\n'.join(errors))
    instructions = Path(instructions_file).read_text(encoding='utf-8') if instructions_file else None
    result = prepare_migration(files, instructions=instructions)
    result['needs_update'] = bool(result['writes']) if result['status'] != 'blocked' else None
    if result['status'] in {'blocked', 'no_op'}:
        return result
    candidate = store.apply_writes(files, result['writes'])
    # A verified receipt describes the prior physical content. Validate changed
    # candidates as unresolved; the coordinator refreshes their synchronization
    # through its ordinary projection comparison and backend readback rules.
    validation_files = dict(candidate)
    receipt_refresh = []
    for identifier in store.items(candidate):
        receipt = store.receipt(files, identifier)
        if (receipt and receipt.get('state') == 'verified' and
                receipt.get('content_sha256') != runtime._business_digest(candidate, identifier)):
            receipt_refresh.append(identifier)
            validation_files.update(store.apply_writes({}, store.write_receipt(
                candidate, identifier, dict(receipt, state='unknown'))))
    if receipt_refresh and store.project(candidate).get('backends', {}).get('aone') is None:
        result.update(status='blocked', code='aone-configuration-required', writes={}, checks={},
                      blockers=[f'{identifier}: verified receipt changes but project.backends.aone is not configured'
                                for identifier in receipt_refresh],
                      action='Restore the configured Aone backend needed to revalidate these current receipts before migration.')
        return result
    errors = runtime._validate_files(root, validation_files)
    if errors:
        raise runtime.ProjectError('invalid migration candidate:\n' + '\n'.join(errors))
    result['validated'] = True
    if receipt_refresh:
        result['backend_sync_required'] = receipt_refresh
        result['validation_scope'] = 'Structural candidate validated; the publication coordinator must create new intents and verify backend readback for the changed physical snapshot.'
    if dry_run:
        return result
    if publish is None:
        raise runtime.ProjectError('migration requires the guarded publication coordinator; use dry_run to inspect')
    operation = uuid.uuid4().hex
    identity = {'session': 'project-migration', 'token': operation, 'machine': platform.node() or 'localhost',
                'migration': True}
    result.update(status='partial', migration_operation=operation)
    record = {'identity': identity, 'result': result}
    path = _intent_path(root, operation)
    try:
        path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        runtime._write_journal(path, record)
    except OSError as exc:
        return dict(result, status='blocked', code='migration_intent_not_saved', error=str(exc), completion='incomplete')
    return _publish_intent(root, record, publish)
